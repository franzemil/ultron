/*
 * infer — TFLite-Micro interpreter wrapper (spec 003 T12, TD-004).
 *
 * Runtime choice (design.md TD-004): TFLite-Micro from the Arduino/ESP32
 * ecosystem, driven through the raw TFLM API — a static
 * `alignas(16) uint8_t tensor_arena[]`, `tflite::MicroInterpreter` with
 * `tflite::AllOpsResolver`, and the flatbuffer as a `const unsigned char[]`.
 * Edge Impulse's `Lampara_inferencing` runtime is explicitly rejected
 * (EI is export-only — AGENTS rule 3), and so is an ESP-IDF rewrite.
 *
 * The ArduTFLite wrapper is NOT used: its `modelSetInput(float, index)` targets
 * single-scalar models, while this one takes a `[1, 100, 13]` int8 tensor, so
 * the TfLiteTensor is driven directly.
 *
 * Model bytes: `model_data.h`, generated by scripts/gen_esp32_model.py from
 * `build/model_int8.tflite` (gitignored — a model artifact never lands in git).
 * The committed copy is the deterministic PLACEHOLDER (random weights, same
 * signature and class order as spec 002's artifact); see the header banner.
 *
 * Static-only: no allocation in the inference path. The arena is 150 KB
 * (NFR-002 budget); `arena_used` is reported at boot for the memory table.
 */

#ifndef ULTRON_INFER_H
#define ULTRON_INFER_H

#include <stddef.h>
#include <stdint.h>

namespace ultron {

/* NFR-002: TFLM arena ≤ 150 KB. The reservation is 64 KB by default:
 * design.md estimates 16-32 KB for this architecture and the analytic activation
 * bound for a ~3 k-parameter KwsNet is ~6 KB, so 64 KB leaves 2-4x headroom while
 * keeping the inference path (arena + 64 KB ring + MFCC) inside the 240 KB RAM
 * budget. Raise it for a bigger future model without touching code:
 *   --build-property "compiler.cpp.extra_flags=-DULTRON_ARENA_KB=128"
 * Boot logs `arena_used`; if a model ever needs more the firmware fails loud
 * with EVT ERROR code=ARENA_TOO_SMALL instead of misbehaving. */
#ifndef ULTRON_ARENA_KB
#define ULTRON_ARENA_KB 64
#endif
static constexpr size_t kTensorArenaBytes = (size_t)ULTRON_ARENA_KB * 1024;

struct ModelStats {
  size_t model_bytes = 0;   /* flatbuffer size (int8 flash budget ≤ 100 KB) */
  size_t arena_bytes = 0;   /* statically reserved arena                    */
  size_t arena_used = 0;    /* bytes the interpreter actually mapped        */
  int n_classes = 0;        /* output width — must equal the frozen order   */
  int n_frames = 0;         /* input frames (100)                           */
  int n_coeffs = 0;         /* input coefficients (13)                      */
  bool input_nwc = true;    /* flatbuffer layout: [1,100,13] (NWC) or       */
                            /* [1,13,100] (NCW — what onnx2tf emits here)   */
  float input_scale = 0.0f; /* int8 asymmetric input quantization           */
  int input_zero_point = 0;
  float output_scale = 0.0f;
  int output_zero_point = 0;
  bool placeholder = false; /* true when the embedded flatbuffer is the       */
                            /* deterministic placeholder, not spec 002's    */
                            /* trained artifact                             */
  const char *provenance = "";
};

/* Parse the flatbuffer and allocate the tensors. Returns:
 *   0  ok
 *   1  flatbuffer / schema mismatch
 *   2  AllocateTensors() failed (arena too small)
 *   3  input signature is not [1, 100, 13] / [1, 13, 100] int8
 *   4  output is not int8 with one score per frozen class
 *
 * The layout is *detected*, never assumed: the repo's own exporter tolerates
 * both (export.py → _run_tflite) and onnx2tf 1.28 / TF 2.21 emit NCW
 * [1, 13, 100] on this machine. Features are always produced in NWC order
 * (100 frames x 13), and infer_run transposes when the model wants NCW. */
int infer_begin(ModelStats *stats);

/* Run one 2 s window: features is exactly 100*13 int8 values, already
 * quantized with the interpreter's input scale/zero point. Fills `scores` with
 * dequantized probabilities (the model's softmax is inside the graph).
 * Returns 0 on success, non-zero on a TFLM error. */
int infer_run(const int8_t *features, float *scores, int n_classes);

/* Last invocation duration in microseconds (NFR-001 ≤ 400 ms). */
uint32_t infer_lastLatencyUs();

}  // namespace ultron

#endif /* ULTRON_INFER_H */
