"""Output controller host tests — T15 (spec 003-can-act, FR-009 / FR-017 / NFR-009).

``tests/esp32/outputs_engine_test.cpp`` is compiled with the *same* translation unit the
firmware ships (``devices/esp32/ultron_voice/outputs.cpp``) and run with a fake clock. It
asserts the Actuation Behavior Contract timings, priority rules, the edge records the firmware
prints as ``DBG out=`` lines and the NFR-009 fail-safe.

The test needs two command tables, and this module supplies both:

* the **shipped** table — ``ULTRON_COMMANDS[]`` from the generated
  ``devices/esp32/libraries/UltronVoice/src/ultron_config.h``. It is the *trained* subset
  (``la``, ``lb``), because those are the only ``EVT CMD`` ids the state machine can emit today.
* the **contract** table — every command in ``model/registry.json`` (11 today), rendered here
  into ``contract_commands.h`` in the test's build directory. Never committed: the firmware must
  not carry a second hand-written copy of the mapping, and the engine still has to prove all
  seven behaviours before spec 006's rollout trains the phrases.

The generated-header drift guard lives in ``tests/test_esp32_config.py`` (byte-for-byte render
equality plus the behavior/channels carried for the output layer) — it is not duplicated here.

The XIAO's on-device proof (real ``DBG out=`` lines, boot-safe relays) is the firmware log
captured on the bench, not something a host test can stand in for.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
SKETCH_DIR = REPO_ROOT / "devices/esp32/ultron_voice"
LIBRARY_SRC = REPO_ROOT / "devices/esp32/libraries/UltronVoice/src"
TEST_SOURCE = REPO_ROOT / "tests/esp32/outputs_engine_test.cpp"
ENGINE_SOURCE = SKETCH_DIR / "outputs.cpp"
REGISTRY = REPO_ROOT / "model/registry.json"


def _compiler() -> str:
    for candidate in (os.environ.get("CXX"), "c++", "clang++", "g++"):
        if candidate and shutil.which(candidate):
            return candidate
    pytest.skip("no C++ compiler on PATH (set CXX to override)")


def _render_contract_commands(registry_path: Path = REGISTRY) -> str:
    """model/registry.json → `contract_commands.h` (the engine's test fixture)."""
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    rows = []
    for cmd in registry["commands"]:
        cmd_id = json.dumps(str(cmd["id"]))
        behavior = json.dumps(str(cmd.get("behavior", "")))
        channels = json.dumps(",".join(str(ch) for ch in cmd.get("channels", [])))
        rows.append(f"    {{{cmd_id}, {behavior}, {channels}}},")
    return "\n".join(
        [
            "/* GENERATED by tests/test_esp32_outputs.py from model/registry.json.",
            " * Test fixture only — never compiled into the firmware. */",
            "static const TestCommandRow kContractCommands[] = {",
            *rows,
            "};",
            f"static const size_t kContractCommandCount = {len(rows)};",
            "",
        ]
    )


def test_output_engine_host_timings(tmp_path: Path) -> None:
    fixture = tmp_path / "contract_commands.h"
    fixture.write_text(_render_contract_commands(), encoding="utf-8")

    exe = tmp_path / "outputs_engine_test"
    cmd = [
        _compiler(),
        "-std=c++17",
        "-O2",
        "-Wall",
        "-Wextra",
        f"-I{SKETCH_DIR}",
        f"-I{LIBRARY_SRC}",
        f"-I{tmp_path}",
        str(TEST_SOURCE),
        str(ENGINE_SOURCE),
        "-o",
        str(exe),
    ]
    build = subprocess.run(cmd, capture_output=True, text=True)
    assert build.returncode == 0, f"compile failed:\n{' '.join(cmd)}\n{build.stderr}"

    run = subprocess.run([str(exe)], capture_output=True, text=True, timeout=300)
    assert run.returncode == 0, f"engine test failed:\n{run.stdout}\n{run.stderr}"
    assert "outputs_engine_test: OK" in run.stdout


def test_contract_fixture_matches_the_registry() -> None:
    """The rendered fixture must be exactly model/registry.json (no hand-copy drift)."""
    text = _render_contract_commands()
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    for cmd in registry["commands"]:
        channels = ",".join(str(ch) for ch in cmd.get("channels", []))
        assert f'{{"{cmd["id"]}", "{cmd.get("behavior", "")}", "{channels}"}}' in text
    assert f"kContractCommandCount = {len(registry['commands'])};" in text


if __name__ == "__main__":  # pragma: no cover
    sys.exit(pytest.main([__file__, "-v"]))
